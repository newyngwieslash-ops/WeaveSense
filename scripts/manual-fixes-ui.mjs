import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { chromium } from 'playwright';
const origin = process.argv[2] || 'http://127.0.0.1:8182';
const browser = await chromium.launch({ headless: true });
const errors = [];
mkdirSync('screenshots', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(origin + '/model-settings');
  const model = page.getByLabel('模型 ID', {exact:true});
  await model.waitFor();
  const saved = await model.inputValue();
  await model.fill('回归未保存草稿');
  assert.equal(await page.getByRole('button', {name:'测试连接',exact:true}).isDisabled(), true);
  await page.getByRole('button', {name:'重新读取',exact:true}).click();
  await page.waitForFunction(v => document.querySelector('#model-id')?.value === v || [...document.querySelectorAll('input')].some(i => i.value === v), saved);
  assert.equal(await model.inputValue(), saved);
  await page.goto(origin + '/inbox?platform=rss&media=article&q=理想');
  const link = page.locator('a[href*="/inbox/"]').first();
  await link.waitFor();
  const before = new URL(page.url()).search;
  await link.click();
  await page.getByRole('link', {name:'返回内容'}).waitFor();
  const detail = page.url();
  await page.getByRole('link', {name:'返回内容'}).click();
  assert.equal(new URL(page.url()).search, before);
  await page.goto(detail);
  await page.locator('article').waitFor();
  await page.screenshot({path:'screenshots/manual-fixes-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(300);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const overflow = await page.locator('article, aside, dd').evaluateAll(nodes => nodes.filter(n => n.scrollWidth > n.clientWidth + 1).map(n => n.tagName));
  assert.deepEqual(overflow, []);
  await page.screenshot({path:'screenshots/manual-fixes-mobile.png'});
  await page.locator('aside').last().scrollIntoViewIfNeeded();
  await page.screenshot({path:'screenshots/manual-fixes-mobile-fields.png'});
  assert.deepEqual(errors, []);
  console.log('PASS: reload draft, return filters, desktop/mobile detail, no page errors; no model action submitted');
} finally { await browser.close(); }
